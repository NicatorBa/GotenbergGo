// Command generator generates the request builders, stage builders and enum
// types of the gotenberg package from the YAML definitions in this directory.
//
// It is invoked from the root module via go generate:
//
//	//go:generate go -C generator run . -out ..
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const header = "// Code generated by github.com/NicatorBa/GotenbergGo/generator. DO NOT EDIT.\n\n"

func main() {
	out := flag.String("out", "..", "output directory, the root of the gotenberg package")
	flag.Parse()

	err := run(".", *out)
	if err != nil {
		fmt.Fprintln(os.Stderr, "generator:", err)
		os.Exit(1)
	}
}

func run(dir, out string) error {
	defs, err := load(dir)
	if err != nil {
		return err
	}

	// Remove the previous output, so that a deleted definition leaves no
	// stale file behind.
	stale, err := filepath.Glob(filepath.Join(out, "*_gen*.go"))
	if err != nil {
		return err
	}

	for _, path := range stale {
		err := os.Remove(path)
		if err != nil {
			return err
		}
	}

	g := &gen{defs: defs}

	files := map[string]string{
		"enums_gen.go":      g.enums(),
		"enums_gen_test.go": g.enumsTest(),
	}

	for _, b := range defs.Builders {
		files[b.file+"_gen.go"] = g.builder(b)
		files[b.file+"_gen_test.go"] = g.builderTest(b)
	}

	for _, op := range defs.Ops {
		files["pdf_"+op.file+"_gen.go"] = g.op(op)
		files["pdf_"+op.file+"_gen_test.go"] = g.opTest(op)
	}

	for _, name := range sortedKeys(files) {
		err := writeGo(filepath.Join(out, name), files[name])
		if err != nil {
			return err
		}
	}

	return nil
}

// writeGo adds the header and the imports the body uses, formats the source
// and writes it.
func writeGo(path, body string) error {
	// Doc comments may mention package names: only code lines count.
	var code strings.Builder
	for _, line := range strings.Split(body, "\n") {
		if !strings.HasPrefix(strings.TrimSpace(line), "//") {
			code.WriteString(line + "\n")
		}
	}

	var imports []string
	for _, pkg := range []struct{ path, use string }{
		{"context", "context."},
		{"encoding/json", "json."},
		{"io", "io."},
		{"io/fs", "fs."},
		{"net/http", "http."},
		{"testing", "testing."},
		{"time", "time."},
		{"github.com/stretchr/testify/assert", "assert."},
		{"github.com/stretchr/testify/require", "require."},
	} {
		if regexp.MustCompile(`(^|[^\w.])` + regexp.QuoteMeta(pkg.use)).MatchString(code.String()) {
			imports = append(imports, fmt.Sprintf("%q", pkg.path))
		}
	}

	src := header + "package gotenberg\n\n"
	if len(imports) > 0 {
		src += "import (\n" + strings.Join(imports, "\n") + "\n)\n\n"
	}

	src += body

	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("format %s: %w\n%s", path, err, src)
	}

	return os.WriteFile(path, formatted, 0o644)
}
